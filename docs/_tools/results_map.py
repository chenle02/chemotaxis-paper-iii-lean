#!/usr/bin/env python3
"""Write docs/results.md: the results of docs/verification.md grouped by paper section.

docs/verification.md is generated by `lean-pkg page`; this map only re-indexes it. Each entry
links to the result's heading on the generated page and repeats that page's own hypotheses
class; no claim text is written here. Jekyll skips this `_tools` directory.

  python3 docs/_tools/results_map.py           rewrite docs/results.md
  python3 docs/_tools/results_map.py --check   exit 1 when docs/results.md is stale
"""
import pathlib
import re
import sys

DOCS = pathlib.Path(__file__).resolve().parent.parent
SOURCE = DOCS / "verification.md"
TARGET = DOCS / "results.md"

# Section titles of the October 20, 2026 v2 manuscript (\section commands), without the
# "and proof of Theorem ..." suffixes.
SECTIONS = {
    1: "Introduction",
    2: "Local bifurcation of constant solutions",
    3: "Effects of β and L on the bifurcation",
    4: "Extension of the local bifurcation branches",
    5: "Spike-like stationary solutions",
    6: "Numerical analysis of the bifurcation and spike-like solutions",
}
OWN = "The paper's own"
EXTRA = "The paper's, plus these"
CLASSES = {OWN: "paper's own hypotheses", EXTRA: "extra hypotheses"}


def anchor(title: str, seen: dict) -> str:
    """The id kramdown (GitHub Pages) gives a heading: lower case, punctuation dropped,
    spaces to hyphens, repeats suffixed -1, -2, ..."""
    text = title.replace("\\_", "_").replace("&lt;", "").replace("&gt;", "").replace("&amp;", "")
    slug = re.sub(r"[^a-z0-9 _-]", "", text.lower()).replace(" ", "-")
    n = seen.get(slug, 0)
    seen[slug] = n + 1
    return slug if n == 0 else f"{slug}-{n}"


def parse(md: str):
    """(results, not_formalized): results are (section, title, anchor, class) in page order."""
    results, missing, seen = [], [], {}
    lines = md.splitlines()
    in_results = in_missing = False
    for i, line in enumerate(lines):
        if line.startswith("## "):
            anchor(line[3:], seen)
            in_results = line == "## The paper's results in Lean"
            in_missing = line == "## Not formalized"
            continue
        if line.startswith("### "):
            title = line[4:]
            slug = anchor(title, seen)
            if not in_results:
                continue
            cls = None
            for nxt in lines[i + 1:]:
                if nxt.startswith("#"):
                    break
                if nxt.startswith("**Hypotheses.** "):
                    body = nxt[len("**Hypotheses.** "):]
                    cls = next((v for k, v in CLASSES.items() if body.startswith(k)), None)
                    break
            m = re.search(r"(\d+)\.\d+", title)
            results.append((int(m.group(1)) if m else 0, title, slug, cls))
        elif in_missing and line.startswith("- "):
            missing.append(line[2:].split(":", 1)[0])
    return results, missing


def render(results, missing) -> str:
    own = sum(1 for r in results if r[3] == CLASSES[OWN])
    extra = sum(1 for r in results if r[3] == CLASSES[EXTRA])
    out = [
        "---",
        "title: Results by paper section",
        "description: Every formalized result of Chemotaxis III, grouped by the manuscript section that states it.",
        "---",
        "",
        "<!-- Generated by docs/_tools/results_map.py from docs/verification.md. Do not edit by hand. -->",
        "",
        "# Results by paper section",
        "",
        "Each entry opens the result on the [verification page](verification.html), which shows the",
        "Lean statement, its hypotheses, the checks that ran and, where it is quoted, the paper's",
        "statement. The class in",
        "brackets repeats that page's own wording. Section titles follow the October 20, 2026 v2",
        "manuscript; results are grouped by the section whose number they carry.",
        "",
        f"Listed here: {len(results)} results ({own} with the paper's own hypotheses, {extra} with extra",
        f"hypotheses) and {len(missing)} not formalized.",
        "",
    ]
    for sec in sorted({r[0] for r in results}):
        rows = [r for r in results if r[0] == sec]
        name = SECTIONS.get(sec, "Other")
        out += [f"## {sec}. {name}" if sec else "## Other", "",
                f"<details markdown=\"1\"{' open' if sec == 1 else ''}>",
                f"<summary>{len(rows)} result{'s' if len(rows) != 1 else ''}</summary>", ""]
        for _, title, slug, cls in rows:
            out.append(f"- [{title}](verification.html#{slug}){f' ({cls})' if cls else ''}")
        out += ["", "</details>", ""]
    out += ["## Not formalized", "",
            "Listed with their reasons on the [verification page](verification.html#not-formalized):", ""]
    out += [f"- {m}" for m in missing] + [""]
    return "\n".join(out)


def main() -> int:
    text = render(*parse(SOURCE.read_text(encoding="utf-8")))
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
        if current != text:
            print(f"{TARGET.relative_to(DOCS.parent)} is stale: run python3 docs/_tools/results_map.py")
            return 1
        print(f"{TARGET.relative_to(DOCS.parent)} is current")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
